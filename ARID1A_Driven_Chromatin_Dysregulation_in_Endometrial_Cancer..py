def _clean_gene(g):
    """Extract plain gene symbol from any index format."""
    if isinstance(g, tuple):
        return str(g[0])
    s = str(g)
    # Handle string repr of tuple: "('GENE', 'ENSP...')"
    if s.startswith("("):
        import re
        m = re.search(r"[A-Z][A-Z0-9]+", s)
        if m:
            return m.group(0)
    return s.split("_")[0]

